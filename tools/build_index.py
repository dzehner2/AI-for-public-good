#!/usr/bin/env python3
"""Validate idea cards and write a ranked INDEX.md.

Usage (from the repo root):
    python3 ai-for-public-good/tools/build_index.py

Standard library only. Exits with status 1 if any card is invalid, so it can run in CI.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IDEAS_DIR = ROOT / "ideas"
INDEX_PATH = ROOT / "INDEX.md"

DOMAINS = {"water", "air", "land", "community", "cross-cutting"}
STATUSES = {"seed", "researching", "designed", "piloting", "scaled", "retired"}

# Score keys match the rubric. Weights match rubric.md.
WEIGHTS = {
    "footprint": 2.0,
    "governance": 2.0,
    "community": 1.5,
    "water": 1.5,
    "air": 1.5,
    "land": 1.5,
    "feasibility": 1.0,
    "data": 1.0,
}
GATED = {"footprint", "governance"}  # a score of 1 on these blocks the idea

REQUIRED_FIELDS = {"id", "title", "status", "domain"}

FRONT_MATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)


def parse_front_matter(text):
    match = FRONT_MATTER.match(text)
    if not match:
        return None
    fields = {}
    for line in match.group(1).splitlines():
        if not line.strip():
            continue
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    return fields


def validate(path, fields):
    errors = []
    missing = REQUIRED_FIELDS - fields.keys()
    if missing:
        errors.append(f"missing fields: {', '.join(sorted(missing))}")
    if fields.get("id") and fields["id"] != path.stem:
        errors.append(f"id '{fields['id']}' must match filename '{path.stem}'")
    if fields.get("domain") and fields["domain"] not in DOMAINS:
        errors.append(f"domain '{fields['domain']}' not one of {sorted(DOMAINS)}")
    if fields.get("status") and fields["status"] not in STATUSES:
        errors.append(f"status '{fields['status']}' not one of {sorted(STATUSES)}")
    for key in WEIGHTS:
        raw = fields.get(f"score_{key}")
        if raw is None:
            errors.append(f"missing score_{key}")
            continue
        if not raw.isdigit() or not 1 <= int(raw) <= 5:
            errors.append(f"score_{key} must be an integer 1-5, got '{raw}'")
    return errors


def scores_of(fields):
    return {key: int(fields[f"score_{key}"]) for key in WEIGHTS}


def weighted_score(scores):
    """Weighted average on the 1-5 scale, rescaled so 1 maps to 0 and 5 maps to 100."""
    total_weight = sum(WEIGHTS.values())
    average = sum(WEIGHTS[k] * scores[k] for k in WEIGHTS) / total_weight
    return round((average - 1) / 4 * 100, 1)


def blocking_gates(scores):
    return sorted(k for k in GATED if scores[k] == 1)


def render_table(rows):
    header = "| Rank | Idea | Domain | Status | Score | Footprint | Governance |"
    divider = "|------|------|--------|--------|-------|-----------|------------|"
    lines = [header, divider]
    for rank, (fields, scores, total) in enumerate(rows, start=1):
        lines.append(
            f"| {rank} | [{fields['title']}](ideas/{fields['id']}.md) | {fields['domain']} "
            f"| {fields['status']} | {total} | {scores['footprint']} | {scores['governance']} |"
        )
    return "\n".join(lines)


def main():
    cards = sorted(IDEAS_DIR.glob("*.md"))
    if not cards:
        print("No idea cards found in", IDEAS_DIR)
        return 1

    ranked, blocked, failures = [], [], []
    for path in cards:
        fields = parse_front_matter(path.read_text(encoding="utf-8"))
        if fields is None:
            failures.append((path, ["missing front matter block"]))
            continue
        errors = validate(path, fields)
        if errors:
            failures.append((path, errors))
            continue
        scores = scores_of(fields)
        total = weighted_score(scores)
        gates = blocking_gates(scores)
        if gates:
            blocked.append((fields, scores, total, gates))
        else:
            ranked.append((fields, scores, total))

    if failures:
        for path, errors in failures:
            for error in errors:
                print(f"{path.relative_to(ROOT)}: {error}", file=sys.stderr)
        return 1

    ranked.sort(key=lambda row: (-row[2], row[0]["id"]))
    blocked.sort(key=lambda row: row[0]["id"])

    by_domain = {}
    for fields, scores, total in ranked:
        by_domain.setdefault(fields["domain"], []).append((fields, scores, total))

    out = [
        "# Idea Index",
        "",
        "_Generated by `ai-for-public-good/tools/build_index.py`. Do not edit by hand._",
        "",
        f"Cards: {len(cards)} total, {len(ranked)} ranked, {len(blocked)} blocked.",
        "",
        "Score is the weighted average of the eight rubric criteria, scaled 0 to 100. "
        "See `rubric.md` for weights and anchors.",
        "",
        "## Ranked ideas",
        "",
        render_table(ranked) if ranked else "_No unblocked ideas yet._",
        "",
        "## By domain",
        "",
    ]
    for domain in sorted(by_domain):
        out.append(f"### {domain.capitalize()}")
        out.append("")
        out.append(render_table(by_domain[domain]))
        out.append("")

    out.append("## Blocked by a hard gate")
    out.append("")
    if blocked:
        out.append("These ideas score 1 on footprint or governance. They stay blocked until the card "
                   "records a mitigation and the score is revised.")
        out.append("")
        out.append("| Idea | Gate | Score |")
        out.append("|------|------|-------|")
        for fields, _scores, total, gates in blocked:
            out.append(f"| [{fields['title']}](ideas/{fields['id']}.md) | {', '.join(gates)} | {total} |")
    else:
        out.append("_None._")
    out.append("")

    INDEX_PATH.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {INDEX_PATH.relative_to(ROOT.parent)}: {len(ranked)} ranked, {len(blocked)} blocked")
    return 0


if __name__ == "__main__":
    sys.exit(main())
